-- DATABASE CREATION
CREATE DATABASE Hospital_Management_System;
USE Hospital_Management_System;

-- CREATE THE TABLE STRUCTURE

CREATE TABLE PATIENTS(
PATIENTS_ID INT PRIMARY KEY AUTO_INCREMENT,
PATIENTS_NAME VARCHAR (100),
GENDER VARCHAR (10),
AGE INT,
PHONE VARCHAR (20),
CITY VARCHAR (30),
ADMISSION_DATE date
);

--  CREATE THE DOCTORS TABLE  

CREATE TABLE DOCTORS(
DOCTORS_ID INT PRIMARY KEY AUTO_INCREMENT,
DOCTORS_NAME VARCHAR(100),
SPECIALIZATION VARCHAR (100),
SALLARY DECIMAL(10,2),
EXPERIENCE_YEARS INT
);

--  CREATE THE DEPARTMENTS TABLE 
CREATE TABLE DEPARTMENTS(
DEPARTMENTS_ID INT PRIMARY KEY AUTO_INCREMENT,
DEPARTMENTS_NAME VARCHAR(100)
);
  
-- CREATE THE APPOINTMENTS TABLE

CREATE TABLE APPOINTMENTS(
APPOINTMENTS_ID INT PRIMARY KEY AUTO_INCREMENT,
PATIENTS_ID INT,
DOCTORS_ID INT,
APPOINTMENT_DATE DATE,
APPOINTMENT_STATUS VARCHAR (100),
FOREIGN KEY (PATIENTS_ID) REFERENCES PATIENTS (PATIENTS_ID),
FOREIGN KEY (DOCTORS_ID) REFERENCES DOCTORS (DOCTORS_ID)
);

-- CREATE THE BILLING TABLE 

CREATE TABLE BILLING(
BILL_ID INT PRIMARY KEY AUTO_INCREMENT,
PATIENTS_ID INT,
TOTAL_AMOUNT DECIMAL(10,2),
PAYMENT_STATUS VARCHAR(60),
FOREIGN KEY (PATIENTS_ID) REFERENCES PATIENTS (PATIENTS_ID)
);

--  CREATE THE MEDICINES TABLE

CREATE TABLE MEDICINES(
MEDICINE_ID INT PRIMARY KEY AUTO_INCREMENT,
MEDICINE_NAME VARCHAR (100),
COMPANY_NAME VARCHAR(50),
PRICE DECIMAL (10,2),
STOCK_QUANTITY INT
);

-- CREATE THE PRESCRIPTIONS TABLE 

CREATE TABLE PRESCRIPTIONS(
PRESCRIPTION_ID INT PRIMARY KEY AUTO_INCREMENT,
PATIENTS_ID INT,
DOCTORS_ID INT,
MEDICINE_ID INT,
DOSAGE VARCHAR (100),
FOREIGN KEY (PATIENTS_ID) REFERENCES PATIENTS(PATIENTS_ID),
FOREIGN KEY (DOCTORS_ID) REFERENCES DOCTORS(DOCTORS_ID),
FOREIGN KEY (MEDICINE_ID) REFERENCES MEDICINES(MEDICINE_ID)
);

