-- VIEW ALL PATIENTS 
SELECT * FROM PATIENTS;

-- VIEW ALL DOCOTEOR
SELECT * FROM DOCTORS;

-- Find Doctors with Experience Above 10 Years
SELECT * FROM DOCTORS
WHERE EXPERIENCE_YEARS >10;

-- Total Billing Amount
SELECT SUM(TOTAL_AMOUNT)AS TOTAL_BILLING
FROM BILLING;

-- Average Doctor Salary
SELECT AVG(SALLARY) AS AVERAGE_SALARY
FROM DOCTORS;

--  JOIN Queries
-- Patient Appointment Report  
SELECT P.PATIENTS_NAME,
       D.DOCTORS_NAME, 
       A.APPOINTMENT_DATE,
       A.APPOINTMENT_STATUS
FROM APPOINTMENTS A
JOIN PATIENTS P ON A.PATIENTS_ID = P.PATIENTS_ID
JOIN DOCTORS D ON A.DOCTORS_ID = D.DOCTORS_ID;


-- PRESCRIPTIONS REPORT
SELECT
    P.PATIENTS_NAME,
    D.DOCTORS_NAME,
    M.MEDICINE_NAME,
    PR.DOSAGE
FROM PRESCRIPTIONS PR
JOIN PATIENTS P
ON PR.PATIENTS_ID = P.PATIENTS_ID
JOIN DOCTORS D
ON PR.DOCTORS_ID = D.DOCTORS_ID
JOIN MEDICINES M
ON PR.MEDICINE_ID = M.MEDICINE_ID;

--  GROUP BY QUERIES
-- Total Patients by City
SELECT CITY,
COUNT(PATIENTS_ID) AS TOTAL_PATIENTS
FROM PATIENTS
GROUP BY CITY;

--  Total Appointments by Doctor
SELECT DOCTORS_ID,
COUNT(APPOINTMENTS_ID) AS TOTAL_APPOINTMENTS 
FROM APPOINTMENTS
GROUP BY DOCTORS_ID; 

--   Subquery Example
-- Find Doctors with Salary Above Average
SELECT DOCTORS_NAME, 
SALLARY FROM DOCTORS
WHERE SALLARY >
( SELECT AVG(SALLARY) FROM DOCTORS);

